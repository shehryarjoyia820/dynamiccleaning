## What is SAE J1667?

SAE J1667 is a published test procedure for measuring smoke from heavy-duty diesel engines. It gives testers a repeatable way to load the engine and read exhaust opacity, so results are comparable from truck to truck. CARB uses this kind of snap-acceleration test for older diesel vehicles in its programs.

"Opacity" simply means how much the exhaust smoke blocks light. Clean exhaust lets light through. Heavy black smoke blocks a lot of it.

## How does the J1667 snap acceleration test work?

In general terms, the test goes like this:

1. **The truck is parked and warmed up.** The engine should be at normal operating temperature, with the transmission in neutral and the wheels chocked.
2. **The opacity meter is set up.** A sensor is placed at the exhaust outlet to read the smoke.
3. **The engine is snapped.** From idle, the accelerator is pressed quickly to the floor and released, letting the engine rev up and come back down.
4. **This is repeated.** A series of snaps is done so the reading reflects the engine, not one odd puff.
5. **The result is compared to the limit.** The measured opacity is checked against CARB''s limit for that engine''s model year.

