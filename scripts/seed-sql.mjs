// Generates supabase/seed.sql from src/content/seed.ts (Node 22.18+ strips TS types natively).
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { FAQS, POSTS, SERVICE_AREAS, SETTINGS } from '../src/content/seed.ts';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = (list, cols) => list.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n');

const sql = `-- Generated by scripts/seed-sql.mjs. Safe to re-run: existing rows are left unchanged.

insert into public.service_areas (slug, name, region, intro, lat, lng, sort) values
${rows(SERVICE_AREAS, ['slug', 'name', 'region', 'intro', 'lat', 'lng', 'sort'])}
on conflict (slug) do nothing;

insert into public.faqs (id, question, answer, category, sort) values
${rows(FAQS, ['id', 'question', 'answer', 'category', 'sort'])}
on conflict (id) do nothing;

insert into public.posts (slug, title, excerpt, body, published_at, published) values
${POSTS.map((p) => `  (${[p.slug, p.title, p.excerpt, p.body, p.published_at].map(q).join(', ')}, true)`).join(',\n')}
on conflict (slug) do nothing;

insert into public.site_settings (key, value) values
${Object.entries(SETTINGS).map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb)`).join(',\n')}
on conflict (key) do nothing;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Wrote supabase/seed.sql');
